import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import JSZip from 'jszip';
import { PDFDocument } from 'pdf-lib';
import sharp from 'sharp';

const run = promisify(execFile);

/** Noisy image so that compression has something real to remove. */
async function noise(width: number, height: number, channels: 3 | 4 = 3): Promise<Buffer> {
  const raw = Buffer.alloc(width * height * channels);
  for (let i = 0; i < raw.length; i++) raw[i] = (i * 31 + (i >> 5) * 17 + Math.floor(Math.random() * 40)) & 0xff;
  return sharp(raw, { raw: { width, height, channels } }).jpeg({ quality: 100 }).toBuffer();
}

export async function makeJpeg(width = 1600, height = 1200, quality = 100): Promise<Buffer> {
  const base = await noise(width, height);
  return sharp(base).jpeg({ quality }).toBuffer();
}

export async function makeJpegWithExif(): Promise<Buffer> {
  return sharp(await makeJpeg(400, 300))
    .withExif({ IFD0: { Copyright: 'tero-private-copyright', Artist: 'secret-artist' } })
    .jpeg({ quality: 95 })
    .toBuffer();
}

export async function makePng(width = 300, height = 200): Promise<Buffer> {
  return sharp({ create: { width, height, channels: 3, background: '#3366cc' } })
    .png()
    .toBuffer();
}

export async function makePdfWithPhoto(): Promise<Buffer> {
  const pdf = await PDFDocument.create();
  const img = await pdf.embedJpg(await makeJpeg(2400, 1800, 98));
  const page = pdf.addPage([595, 842]);
  page.drawImage(img, { x: 20, y: 200, width: 555, height: 416 });
  return Buffer.from(await pdf.save());
}

export async function makeTextPdf(): Promise<Buffer> {
  const pdf = await PDFDocument.create();
  pdf.addPage([300, 300]).drawText('hello tero');
  return Buffer.from(await pdf.save());
}

export async function makeDocx(withLargeImage = true): Promise<Buffer> {
  const zip = new JSZip();
  zip.file(
    '[Content_Types].xml',
    '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>',
  );
  zip.file(
    'word/document.xml',
    '<?xml version="1.0"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body/></w:document>',
  );
  if (withLargeImage) zip.file('word/media/image1.jpeg', await makeJpeg(2000, 1400, 100));
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

/** Tiny real MP4 generated by ffmpeg's test source (video + audio). */
export async function makeMp4(seconds = 2): Promise<Buffer> {
  const out = path.join(os.tmpdir(), `tero-fixture-${process.pid}-${Date.now()}.mp4`);
  await run('ffmpeg', [
    '-y',
    '-hide_banner',
    '-loglevel',
    'error',
    '-f',
    'lavfi',
    '-i',
    `testsrc2=size=1280x720:rate=30:duration=${seconds}`,
    '-f',
    'lavfi',
    '-i',
    `sine=frequency=440:duration=${seconds}`,
    '-c:v',
    'libx264',
    '-preset',
    'ultrafast',
    '-crf',
    '14',
    '-pix_fmt',
    'yuv420p',
    '-c:a',
    'aac',
    out,
  ]);
  try {
    return await fs.readFile(out);
  } finally {
    await fs.rm(out, { force: true });
  }
}

