/** A PDF whose only image is a lossless (Flate) RGB PNG, like an embedded screenshot. */
export async function makePdfWithFlateImage(): Promise<Buffer> {
  const w = 900;
  const h = 700;
  const raw = Buffer.alloc(w * h * 3);
  for (let i = 0; i < raw.length; i++) raw[i] = (i * 7 + (i >> 4) * 13 + Math.floor(Math.random() * 30)) & 0xff;
  const png = await sharp(raw, { raw: { width: w, height: h, channels: 3 } })
    .png({ compressionLevel: 6 })
    .toBuffer();
  const pdf = await PDFDocument.create();
  const img = await pdf.embedPng(png);
  pdf.addPage([595, 842]).drawImage(img, { x: 20, y: 200, width: 555, height: 432 });
  return Buffer.from(await pdf.save());
}
